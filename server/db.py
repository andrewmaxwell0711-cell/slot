"""SQLite + Postgres connection adapter.

Uses DATABASE_URL (Postgres via psycopg) when set, otherwise SQLite at
server/ledger.db. Tests can reassign ledger.DB_PATH to force a temp SQLite
file even if DATABASE_URL is present.

Placeholder conversion (? → %s) and a few DDL tweaks are applied only for
Postgres. Secrets in DATABASE_URL are never logged.
"""

from __future__ import annotations

import os
import re
import sqlite3
import threading
from pathlib import Path
from typing import Any, Iterable, Sequence

DEFAULT_SQLITE_PATH = Path(__file__).resolve().parent / "ledger.db"

_local = threading.local()


def database_url() -> str:
    return (os.environ.get("DATABASE_URL") or "").strip()


def is_postgres(sqlite_path: Path | str | None = None) -> bool:
    """Postgres only when DATABASE_URL is set and no explicit SQLite override."""
    if sqlite_path is not None and Path(sqlite_path) != DEFAULT_SQLITE_PATH:
        return False
    url = database_url()
    return url.startswith("postgres://") or url.startswith("postgresql://")


def backend_name(sqlite_path: Path | str | None = None) -> str:
    return "postgres" if is_postgres(sqlite_path) else "sqlite"


def table_columns(conn: Any, table: str) -> set[str]:
    ident = _safe_ident(table)
    if getattr(conn, "postgres", False):
        rows = conn.execute(
            """
            SELECT column_name AS name
            FROM information_schema.columns
            WHERE table_schema = current_schema() AND table_name = ?
            """,
            (ident,),
        ).fetchall()
        return {r["name"] for r in rows}
    rows = conn.execute(f"PRAGMA table_info({ident})").fetchall()
    return {r["name"] for r in rows}


def _safe_ident(name: str) -> str:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name or ""):
        raise ValueError("Invalid table name")
    return name


def adapt_sql(sql: str, postgres: bool) -> str:
    if not postgres:
        # SQLite rejects FOR UPDATE; BEGIN IMMEDIATE already serialises writers.
        return re.sub(r"\s+FOR UPDATE\b", "", sql, flags=re.I)
    stripped = sql.strip()
    if stripped.upper().startswith("PRAGMA "):
        return ""
    if re.match(r"BEGIN\s+IMMEDIATE\b", stripped, re.I):
        return "BEGIN"
    sql = _adapt_ddl(sql)
    sql = _replace_placeholders(sql)
    return sql


def _adapt_ddl(sql: str) -> str:
    sql = re.sub(
        r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        sql,
        flags=re.I,
    )
    sql = re.sub(
        r"INSERT\s+OR\s+IGNORE\s+INTO",
        "INSERT INTO",
        sql,
        flags=re.I,
    )
    # If we stripped OR IGNORE, append ON CONFLICT DO NOTHING when missing.
    if re.search(r"^\s*INSERT\s+INTO\b", sql, re.I | re.S) and "ON CONFLICT" not in sql.upper():
        # Only for statements that originated as OR IGNORE (we already rewrote
        # the keyword). Callers should prefer explicit ON CONFLICT in source.
        # Detect via a preceding rewrite is gone; leave explicit inserts alone
        # unless the helper insert_or_ignore is used. No automatic append here.
        pass
    return sql


def _replace_placeholders(sql: str) -> str:
    # Our SQL strings do not embed literal question marks inside quotes.
    return sql.replace("?", "%s")


def split_sql(script: str) -> list[str]:
    parts: list[str] = []
    for stmt in script.split(";"):
        s = stmt.strip()
        if not s:
            continue
        meaningful = [
            ln for ln in s.splitlines()
            if ln.strip() and not ln.strip().startswith("--")
        ]
        if meaningful:
            parts.append(s)
    return parts


class Row(dict):
    """dict-like row that also supports index access and .keys() like sqlite3.Row."""

    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)

    def keys(self) -> Any:  # type: ignore[override]
        return super().keys()


def _row_from_cursor(cur: Any, raw: Any) -> Row | None:
    if raw is None:
        return None
    if isinstance(raw, sqlite3.Row):
        return raw  # already name-accessible
    if isinstance(raw, Row):
        return raw
    if isinstance(raw, dict):
        return Row(raw)
    desc = cur.description or ()
    names = [d[0] for d in desc]
    return Row({names[i]: raw[i] for i in range(len(names))})


class Cursor:
    def __init__(self, cur: Any):
        self._cur = cur

    def fetchone(self) -> Any:
        return _row_from_cursor(self._cur, self._cur.fetchone())

    def fetchall(self) -> list[Any]:
        rows = self._cur.fetchall()
        return [_row_from_cursor(self._cur, r) for r in rows]

    def fetchmany(self, size: int | None = None) -> list[Any]:
        rows = self._cur.fetchmany(size) if size is not None else self._cur.fetchmany()
        return [_row_from_cursor(self._cur, r) for r in rows]

    @property
    def lastrowid(self) -> Any:
        return getattr(self._cur, "lastrowid", None)

    @property
    def rowcount(self) -> int:
        return int(getattr(self._cur, "rowcount", -1) or -1)

    def close(self) -> None:
        try:
            self._cur.close()
        except Exception:
            pass

    def __iter__(self) -> Any:
        for r in self._cur:
            yield _row_from_cursor(self._cur, r)


class CompatConn:
    def __init__(self, raw: Any, postgres: bool):
        self._raw = raw
        self.postgres = postgres

    def execute(self, sql: str, params: Sequence[Any] | None = None) -> Cursor:
        adapted = adapt_sql(sql, self.postgres)
        if not adapted.strip():
            return Cursor(_DummyCursor())
        if params is None:
            cur = self._raw.execute(adapted)
        else:
            cur = self._raw.execute(adapted, tuple(params))
        return Cursor(cur)

    def executemany(self, sql: str, seq: Iterable[Sequence[Any]]) -> Cursor:
        adapted = adapt_sql(sql, self.postgres)
        cur = self._raw.execute if False else self._raw.executemany(adapted, list(seq))
        return Cursor(cur)

    def executescript(self, script: str) -> None:
        for stmt in split_sql(script):
            adapted = adapt_sql(stmt, self.postgres)
            if adapted.strip():
                # DDL / multi-statement fragments have no params.
                self._raw.execute(adapted)

    def close(self) -> None:
        try:
            self._raw.close()
        except Exception:
            pass

    def commit(self) -> None:
        if hasattr(self._raw, "commit"):
            try:
                self._raw.commit()
            except Exception:
                pass

    def rollback(self) -> None:
        if hasattr(self._raw, "rollback"):
            try:
                self._raw.rollback()
            except Exception:
                pass


class _DummyCursor:
    description = None

    def fetchone(self) -> None:
        return None

    def fetchall(self) -> list:
        return []

    def fetchmany(self, size: int | None = None) -> list:
        return []

    lastrowid = None
    rowcount = -1

    def close(self) -> None:
        return None

    def __iter__(self):
        return iter(())


def connect(sqlite_path: Path | str | None = None) -> CompatConn:
    if is_postgres(sqlite_path):
        import psycopg

        conn = psycopg.connect(database_url(), autocommit=True)
        return CompatConn(conn, postgres=True)
    path = Path(sqlite_path) if sqlite_path is not None else DEFAULT_SQLITE_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    raw = sqlite3.connect(str(path), check_same_thread=False, isolation_level=None)
    raw.row_factory = sqlite3.Row
    raw.execute("PRAGMA foreign_keys = ON")
    raw.execute("PRAGMA journal_mode = WAL")
    raw.execute("PRAGMA busy_timeout = 20000")
    return CompatConn(raw, postgres=False)


def get_conn(sqlite_path: Path | str | None = None) -> CompatConn:
    conn = getattr(_local, "conn", None)
    if conn is None:
        conn = connect(sqlite_path)
        _local.conn = conn
    return conn


def reset_local() -> None:
    conn = getattr(_local, "conn", None)
    if conn is not None:
        try:
            conn.close()
        except Exception:
            pass
    _local.conn = None
